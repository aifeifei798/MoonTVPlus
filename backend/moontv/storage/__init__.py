"""Storage backend contract — mirrors the `IStorage` interface in `src/lib/types.ts`.

Every method is `async` so the redis/kvrocks backends (real network I/O) and the
sqlite backend share one shape, and the route handlers can `await` uniformly.

Two extras beyond `IStorage`, both present in MoonTV's D1 backend and used by
`/api/admin/data_migration/import`:

    batch_import_*  — bulk write path. In D1 these existed to dodge Cloudflare's
                      per-invocation subrequest limit; for sqlite they are simply
                      one transaction per chunk, which is why `run_batch` keeps
                      the same 100-row chunk size and the same progress callback
                      signature (the SSE progress events in the import route
                      depend on that callback firing once per chunk).

    get_user_password — used by the export route to read `u:<user>:pwd` /
                        `SELECT password FROM users`.
"""

from __future__ import annotations

from typing import Any, Protocol


class Storage(Protocol):
    """Structural contract; implementations need not inherit from this class."""

    # ---------- 播放记录 ----------
    def get_play_record(self, user_name: str, key: str) -> Any: ...
    def set_play_record(self, user_name: str, key: str, record: Any) -> None: ...
    def get_all_play_records(self, user_name: str) -> Any: ...
    def delete_play_record(self, user_name: str, key: str) -> None: ...

    # ---------- 收藏 ----------
    def get_favorite(self, user_name: str, key: str) -> Any: ...
    def set_favorite(self, user_name: str, key: str, favorite: Any) -> None: ...
    def get_all_favorites(self, user_name: str) -> Any: ...
    def delete_favorite(self, user_name: str, key: str) -> None: ...

    # ---------- 追更 ----------
    def get_following(self, user_name: str, key: str) -> Any: ...
    def set_following(self, user_name: str, key: str, following: Any) -> None: ...
    def get_all_followings(self, user_name: str) -> Any: ...
    def delete_following(self, user_name: str, key: str) -> None: ...

    # ---------- 用户 ----------
    def register_user(self, user_name: str, password: str) -> None: ...
    def verify_user(self, user_name: str, password: str) -> bool: ...
    def check_user_exist(self, user_name: str) -> bool: ...
    def change_password(self, user_name: str, new_password: str) -> None: ...
    def delete_user(self, user_name: str) -> None: ...

    # ---------- 搜索历史 ----------
    def get_search_history(self, user_name: str) -> Any: ...
    def add_search_history(self, user_name: str, keyword: str) -> None: ...
    def delete_search_history(self, user_name: str, keyword: str | None = None) -> None: ...

    # ---------- 用户列表 ----------
    def get_all_users(self) -> Any: ...

    # ---------- 管理员配置 ----------
    def get_admin_config(self) -> Any: ...
    def set_admin_config(self, config: Any) -> None: ...

    # ---------- 跳过片头片尾 ----------
    def get_skip_config(self, user_name: str, source: str, id_: str) -> Any: ...
    def set_skip_config(self, user_name: str, source: str, id_: str, config: Any) -> None: ...
    def delete_skip_config(self, user_name: str, source: str, id_: str) -> None: ...
    def get_all_skip_configs(self, user_name: str) -> Any: ...

    # ---------- “今日新更” ----------
    def get_today_updated(self, user_name: str) -> Any: ...
    def set_today_updated(self, user_name: str, record: Any) -> None: ...

    # ---------- 数据清理 ----------
    def clear_all_data(self) -> None: ...
